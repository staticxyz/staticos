#!/usr/bin/env bash
# Калькулятор (SUPER+C): строка rofi в стиле лаунчера, ответ видно сразу, по
# мере набора. Enter — скопировать результат в буфер. Понимает проценты,
# единицы и валюты: 2*17%, 5 km to miles, 150 USD to KZT (qalculate).
#
# Подсказка слева — через -display-calc, а не -p: -p работает только в
# режиме dmenu, а у режима calc rofi писал вместо значка его имя, «calc».
#
# Ответ rofi-calc пишет в виджет message, а в нашей теме (config.rasi) его
# в панели не было — отсюда «ничего не происходит». Здесь он добавлен, а
# пустой список убран: с -no-history строк в нём нет.
#
# Копирует calc_copy.sh — чистый ответ из файла, который пишет обёртка.
# {result} оставлен только как проверенный спуск (с ним Enter точно
# запускал команду); сам скрипт его не читает: rofi-calc подставляет его в
# строку для /bin/sh -c, и узкие пробелы разбивки доезжали битыми байтами.
# (Прежний «мусор» вида «$(0z) * 4 / 0» был честным ответом qalc на
# недописанное «kz» — Enter нажали до того, как дописали «kzt».)
#
# Список children — БЕЗ кавычек: в одной строке после placeholder: "" rofi
# не разбирал [ "inputbar", "message" ] и вешал окно ошибки поверх всего.
#
# Валюты — через «to», а не «in»: qalc читает «in» как дюймы.
#
# qalc — через обёртку calc_qalc.py: курсы она обновляет в фоне, иначе раз
# в сутки вместо ответа всплывала ошибка недоступного coinbase.com.
#
# Переводчик (17.09.2026): текст вместо выражения («hello world», «как дела?»)
# обёртка переводит офлайн (translate_server.py) — это живой предпросмотр.
# Enter (calc_copy.sh) копирует перевод; если есть свой translate_refine.sh —
# уточнённый им, показывая его уведомлением.
#
# Ширина — общая, 520 px из config.rasi (широкую панель пользователь отверг:
# «длиннее по вертикали, не по горизонтали», 23.09.2026). Окно растёт вниз:
# calc_qalc.py режет перевод на строки, а если и сама фраза не влезает в
# однострочный ввод rofi (он сжимает её многоточием), печатает строками и её.
rofi -show calc -modi calc -no-sort -no-history \
     -display-calc "$(printf '\U000f00ec')" \
     -calc-command "$HOME/.config/hypr/scripts/calc_copy.sh '{result}'" \
     -qalc-binary $HOME/.config/hypr/scripts/calc_qalc.py \
     -hint-welcome "" \
     -hint-result "" \
     -theme-str 'entry { placeholder: ""; } panel { children: [ inputbar, message ]; }'
