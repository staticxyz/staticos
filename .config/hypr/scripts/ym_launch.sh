#!/bin/sh
# ym_launch.sh — запустить Яндекс Музыку и применить шрифт системы. 23.09.2026
#
# Сам плеер о шрифте не знает: это Electron с веб-плеером, «YS Text» приходит
# с сервера, и правило fontconfig до него не достаёт. Стиль вливается в окно
# по порту отладки (ym_font.py), но сеанс отладки живёт ровно столько, сколько
# процесс плеера, — значит вливать надо при каждом запуске. Этим и занят
# запускатель: поднимает приложение и сразу отправляет ym_font.py --wait,
# который дожидается появления окна.
#
# Ключи — те же, что в ~/.local/share/applications/yandexmusic.desktop:
# порт 9223 нужен ещё и кнопке «Нравится» в попапе плеера (player_like.py).
#
# Вернуть как было: в .desktop написать прежнюю строку Exec с самим
# /opt/yandex-music/yandexmusic.
HERE="$HOME/.config/hypr/scripts"

"/opt/yandex-music/yandexmusic" --gtk-version=3 \
    --remote-debugging-port=9223 \
    --remote-allow-origins=http://127.0.0.1:9223 "$@" &
app=$!

# В фоне, чтобы не задерживать запуск: ждёт порт, красит страницу и вешает
# стиль на все последующие загрузки документа внутри плеера.
python3 "$HERE/ym_font.py" --wait >/dev/null 2>&1 &

# Размер текста и скрытая плашка об оплате — тем же путём и тоже в фоне
# (25.09.2026). CSS отличить эту плашку от прочих предупреждений не может:
# у всех один класс RedAlert, разница только в тексте.
python3 "$HERE/ym_tweaks.py" --wait >/dev/null 2>&1 &

wait "$app"
